#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
if [[ -z "${DEVELOPER_DIR:-}" && -d /Library/Developer/CommandLineTools ]]; then export DEVELOPER_DIR=/Library/Developer/CommandLineTools; fi
ROOT="$PWD"
SDK="$(xcrun --show-sdk-path)"
ARCH="$(uname -m)"
SIGNING_IDENTITY="${LUMA_SIGNING_IDENTITY:--}"
mkdir -p .build/vendor dist
BYE_ARCHIVE=.build/vendor/byedpi-0.17.3.tar.gz
if [[ ! -f "$BYE_ARCHIVE" ]]; then curl -fLsS --retry 2 https://api.github.com/repos/hufrea/byedpi/tarball/v0.17.3 -o "$BYE_ARCHIVE"; fi
printf '%s  %s\n' '0594a9b612490386436fa3474ba194a0433cd808bc3f278bcfa988dc32acd6d4' "$BYE_ARCHIVE" | shasum -a 256 -c -
mkdir -p .build/vendor/byedpi
# Re-extract the pinned upstream source before each build.
tar -xzf "$BYE_ARCHIVE" -C .build/vendor/byedpi --strip-components=1
patch --batch -d .build/vendor/byedpi -p1 < patches/byedpi-macos-shutdown.patch
make -C .build/vendor/byedpi "CC=$(xcrun --find clang) -isysroot $SDK -mmacosx-version-min=14.0" -j4
if [[ "$ARCH" == arm64 ]]; then TUN_ARCH=arm64;TUN_SHA=7c5ebfe2ffb60ecf6e958cc5bbf3e06e74b8b33575ffbb4ba4f6f785a647f1ad
elif [[ "$ARCH" == x86_64 ]]; then TUN_ARCH=amd64;TUN_SHA=6e654da8bab9ca1645862f0e251a69980e0966680713011feea7b1e5901b2a95
else echo "Unsupported architecture: $ARCH" >&2;exit 1;fi
TUN_ARCHIVE=".build/vendor/tun2socks-2.7.0-$TUN_ARCH.zip"
if [[ ! -f "$TUN_ARCHIVE" ]]; then curl -fLsS --retry 2 "https://github.com/xjasonlyu/tun2socks/releases/download/v2.7.0/tun2socks-darwin-$TUN_ARCH.zip" -o "$TUN_ARCHIVE";fi
printf '%s  %s\n' "$TUN_SHA" "$TUN_ARCHIVE" | shasum -a 256 -c -
unzip -oq "$TUN_ARCHIVE" -d .build/vendor/tun2socks
# Sign outside cloud/File Provider folders; their metadata can race codesign.
STAGING="$(mktemp -d "${TMPDIR:-/tmp}/luma-package.XXXXXX")"
trap 'rm -rf "$STAGING"' EXIT
APP="$STAGING/Luma.app"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/bin" "$APP/Contents/Resources/Licenses" "$APP/Contents/Library/HelperTools" "$APP/Contents/Library/LaunchDaemons"
cp .build/vendor/byedpi/ciadpi "$APP/Contents/Resources/bin/ciadpi"
cp ".build/vendor/tun2socks/tun2socks-darwin-$TUN_ARCH" "$APP/Contents/Resources/bin/tun2socks"
cp Resources/Info.plist "$APP/Contents/Info.plist"
cp Resources/app.luma.gateway.plist "$APP/Contents/Library/LaunchDaemons/"
cp Resources/Licenses/* "$APP/Contents/Resources/Licenses/"
cp LICENSE "$APP/Contents/Resources/Licenses/Luma.txt"
xcrun swift scripts/icon.swift .build/AppIcon.iconset
iconutil -c icns .build/AppIcon.iconset -o "$APP/Contents/Resources/AppIcon.icns"
# Bind the privileged helper to the exact signed tunnel bytes produced by this build.
for executable in "$APP/Contents/Resources/bin/ciadpi" "$APP/Contents/Resources/bin/tun2socks"; do
 chmod 755 "$executable"
 codesign --force --sign "$SIGNING_IDENTITY" --options runtime "$executable"
done
TUN_BINARY_HASH="$(shasum -a 256 "$APP/Contents/Resources/bin/tun2socks" | awk '{print $1}')"
printf '// Generated by scripts/build.sh. Empty source default fails closed.\nlet trustedTunnelSHA256 = "%s"\n' "$TUN_BINARY_HASH" > Sources/LumaGateway/BundledTrust.swift
swift build -c release -Xswiftc -debug-prefix-map -Xswiftc "$ROOT=/src/Luma" -Xswiftc -file-prefix-map -Xswiftc "$ROOT=/src/Luma"
BIN="$(swift build -c release --show-bin-path)"
cp "$BIN/Luma" "$APP/Contents/MacOS/Luma"
cp "$BIN/LumaAgent" "$APP/Contents/Resources/bin/LumaAgent"
cp "$BIN/LumaGateway" "$APP/Contents/Library/HelperTools/LumaGateway"
for executable in "$APP/Contents/MacOS/Luma" "$APP/Contents/Resources/bin/LumaAgent" "$APP/Contents/Library/HelperTools/LumaGateway"; do
 chmod 755 "$executable"
 xcrun strip -S "$executable"
 codesign --force --sign "$SIGNING_IDENTITY" --options runtime "$executable"
done
# File-provider folders can attach Finder metadata to generated bundles.
# Remove only signing-incompatible build metadata, preserving quarantine/provenance.
xattr -dr com.apple.FinderInfo "$APP" 2>/dev/null || true
xattr -dr com.apple.ResourceFork "$APP" 2>/dev/null || true
codesign --force --sign "$SIGNING_IDENTITY" --options runtime "$APP"
codesign --verify --deep --strict "$APP"
ditto --noextattr --norsrc --noqtn -c -k --keepParent "$APP" "$ROOT/dist/Luma-macOS-$ARCH.zip"
# Replace generated output instead of merging stale executables from an older build.
rm -rf "$ROOT/dist/Luma.app"
ditto --norsrc "$APP" "$ROOT/dist/Luma.app"
echo "Built and verified: $ROOT/dist/Luma-macOS-$ARCH.zip"
